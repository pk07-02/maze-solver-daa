-- 1. Create Gameplay Analytics Table
CREATE TABLE GAME_SESSIONS (
    session_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name         VARCHAR2(50) NOT NULL,
    maze_size           VARCHAR2(20) NOT NULL,
    steps_taken         NUMBER NOT NULL,
    solve_time_ms       NUMBER(10, 3) NOT NULL,
    efficiency_score    NUMBER(10, 2),
    played_at           DATE DEFAULT SYSDATE
);

-- 2. Validation Trigger
CREATE OR REPLACE TRIGGER trg_validate_session
BEFORE INSERT ON GAME_SESSIONS
FOR EACH ROW
BEGIN
    IF :NEW.steps_taken <= 0 OR :NEW.solve_time_ms < 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Invalid metrics: Steps and Time must be positive.');
    END IF;
END;
/

-- 3. Stored Function: Efficiency Score
CREATE OR REPLACE FUNCTION calc_efficiency (
    p_steps   IN NUMBER,
    p_time_ms IN NUMBER
) RETURN NUMBER IS
    v_score NUMBER;
BEGIN
    v_score := ROUND(10000 / ((p_steps * 1.5) + (p_time_ms * 10) + 1), 2);
    RETURN v_score;
END calc_efficiency;
/

-- 4. Stored Procedure: Record Maze Session
CREATE OR REPLACE PROCEDURE record_maze_run (
    p_player_name       IN  VARCHAR2,
    p_maze_size         IN  VARCHAR2,
    p_steps             IN  NUMBER,
    p_solve_time_ms     IN  NUMBER,
    p_efficiency_score  OUT NUMBER,
    p_status            OUT VARCHAR2
) AS
BEGIN
    p_efficiency_score := calc_efficiency(p_steps, p_solve_time_ms);

    INSERT INTO GAME_SESSIONS (
        player_name, maze_size, steps_taken, solve_time_ms, efficiency_score, played_at
    ) VALUES (
        p_player_name, p_maze_size, p_steps, p_solve_time_ms, p_efficiency_score, SYSDATE
    );

    COMMIT;
    p_status := 'SUCCESS';
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_status := 'ERROR: ' || SQLERRM;
END record_maze_run;
/

SELECT object_name, object_type, status 
FROM user_objects 
WHERE object_name IN ('GAME_SESSIONS', 'RECORD_MAZE_RUN', 'CALC_EFFICIENCY', 'TRG_VALIDATE_SESSION');

